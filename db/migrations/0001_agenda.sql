-- Same key as central-de-conversas: 55 + DDD + last 8 digits, so the ninth
-- digit never splits one person in two.
CREATE OR REPLACE FUNCTION agenda.phone_key(p text)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE
    WHEN d ~ '^55[1-9][0-9]9?[0-9]{8}$' THEN '55' || substr(d, 3, 2) || right(d, 8)
    ELSE NULLIF(d, '')
  END
  FROM (SELECT regexp_replace(COALESCE(p, ''), '\D', '', 'g') AS d) x
$$;

CREATE TABLE IF NOT EXISTS agenda.meetings (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  calendar_id    text NOT NULL,
  starts_at      timestamptz NOT NULL,
  ends_at        timestamptz NOT NULL,
  status         text NOT NULL DEFAULT 'booked'
                 CHECK (status IN ('booked', 'confirmed', 'done', 'no_show', 'cancelled')),
  phone          text NOT NULL,
  lead_name      text,
  lead_id        text,                       -- db_sales.leads_master.lead_id, when known
  ref            text,                       -- the shared form <-> /agendar reference (F5)
  briefing       jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(briefing) = 'object'),
  booked_by      text NOT NULL CHECK (btrim(booked_by) <> ''),
  gcal_event_id  text UNIQUE,
  meet_url       text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT meetings_time_ck CHECK (ends_at > starts_at),
  CONSTRAINT meetings_no_overlap EXCLUDE USING gist (
    calendar_id WITH =,
    tstzrange(starts_at, ends_at, '[)') WITH &&
  ) WHERE (status IN ('booked', 'confirmed'))
);
CREATE INDEX IF NOT EXISTS meetings_phone_key_idx ON agenda.meetings (agenda.phone_key(phone));

CREATE TABLE IF NOT EXISTS agenda.booking_links (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_sha256  text NOT NULL UNIQUE CHECK (token_sha256 ~ '^[0-9a-f]{64}$'),
  phone         text NOT NULL,
  lead_name     text,
  lead_id       text,
  origem        text NOT NULL CHECK (origem IN ('whatsapp', 'formulario', 'teste')),
  created_by    text NOT NULL CHECK (btrim(created_by) <> ''),
  created_at    timestamptz NOT NULL DEFAULT now(),
  expires_at    timestamptz NOT NULL,
  used_at       timestamptz,
  revoked_at    timestamptz
);

CREATE TABLE IF NOT EXISTS agenda.booking_requests (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at  timestamptz NOT NULL DEFAULT now(),
  origem      text NOT NULL CHECK (origem IN ('publico', 'link')),
  link_id     bigint REFERENCES agenda.booking_links (id),
  ip_hash     text,
  phone_key   text,
  resultado   text NOT NULL CHECK (resultado IN (
    'agendado', 'ja_agendado', 'ja_agendado_ip', 'slot_taken', 'invalido',
    'limite', 'ip_ausente', 'desligado', 'link_invalido')),
  meeting_id  bigint REFERENCES agenda.meetings (id),
  detalhe     jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(detalhe) = 'object')
);
CREATE INDEX IF NOT EXISTS booking_requests_ip_created_idx ON agenda.booking_requests (ip_hash, created_at);

CREATE OR REPLACE FUNCTION agenda.setting(p_key text)
RETURNS jsonb LANGUAGE sql STABLE AS $$
  SELECT value FROM agenda.settings WHERE key = p_key
$$;

-- Private link: the token is returned once; only its sha256 is stored.
CREATE OR REPLACE FUNCTION agenda.create_booking_link(
  p_phone text, p_origem text, p_created_by text,
  p_lead_name text DEFAULT NULL, p_lead_id text DEFAULT NULL, p_ttl interval DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = agenda, pg_temp AS $$
DECLARE
  v_token text;
  v_ttl interval := COALESCE(p_ttl, make_interval(days => (agenda.setting('link_validade_dias') #>> '{}')::int));
  v_id bigint;
  v_expires_at timestamptz;
BEGIN
  IF agenda.phone_key(p_phone) IS NULL
     OR p_origem IS NULL OR p_origem NOT IN ('whatsapp', 'formulario', 'teste')
     OR NULLIF(btrim(p_created_by), '') IS NULL
     OR v_ttl IS NULL OR v_ttl <= interval '0 seconds' THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'invalido');
  END IF;
  v_token := replace(gen_random_uuid()::text, '-', '') || replace(gen_random_uuid()::text, '-', '');
  v_expires_at := now() + v_ttl;
  INSERT INTO agenda.booking_links (token_sha256, phone, lead_name, lead_id, origem, created_by, expires_at)
  VALUES (encode(sha256(convert_to(v_token, 'UTF8')), 'hex'), p_phone, p_lead_name, p_lead_id,
          p_origem, p_created_by, v_expires_at)
  RETURNING id INTO v_id;
  RETURN jsonb_build_object('ok', true, 'link_id', v_id, 'token', v_token, 'expires_at', v_expires_at);
END
$$;

CREATE OR REPLACE FUNCTION agenda.resolve_booking_link(p_token text)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = agenda, pg_temp AS $$
DECLARE
  v_link agenda.booking_links%ROWTYPE;
BEGIN
  IF p_token IS NULL OR p_token !~ '^[0-9a-f]{64}$' THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'link_invalido');
  END IF;
  SELECT * INTO v_link FROM agenda.booking_links
   WHERE token_sha256 = encode(sha256(convert_to(p_token, 'UTF8')), 'hex');
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'link_invalido');
  ELSIF v_link.revoked_at IS NOT NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'link_revogado');
  ELSIF v_link.expires_at <= now() THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'link_vencido');
  ELSIF v_link.used_at IS NOT NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'link_usado');
  END IF;
  RETURN jsonb_build_object('ok', true, 'link_id', v_link.id, 'phone', v_link.phone,
    'lead_name', v_link.lead_name, 'lead_id', v_link.lead_id, 'expires_at', v_link.expires_at);
END
$$;

-- The one write path for a booking. n8n calls it after the Google free/busy
-- re-check and before creating the calendar event; the gist constraint is the
-- last word on two people racing for one slot.
CREATE OR REPLACE FUNCTION agenda.book(
  p_origem text, p_starts_at timestamptz, p_booked_by text,
  p_phone text DEFAULT NULL, p_lead_name text DEFAULT NULL, p_link_token text DEFAULT NULL,
  p_ip_hash text DEFAULT NULL, p_briefing jsonb DEFAULT '{}'::jsonb, p_ref text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = agenda, pg_temp AS $$
DECLARE
  v_link agenda.booking_links%ROWTYPE;
  v_phone text := p_phone;
  v_name text := p_lead_name;
  v_key text;
  v_minutes int := (agenda.setting('meeting_minutes') #>> '{}')::int;
  v_calendar text := agenda.setting('calendar_id') #>> '{}';
  v_reason text;
  v_meeting_id bigint;
  v_request_id bigint;
BEGIN
  IF p_origem IS NULL OR p_origem NOT IN ('publico', 'link') THEN
    v_reason := 'invalido';
  ELSIF COALESCE(agenda.setting('ativa'), 'false'::jsonb) <> 'true'::jsonb THEN
    v_reason := 'desligado';
  ELSIF p_origem = 'publico' AND p_link_token IS NOT NULL THEN
    v_reason := 'invalido';
  ELSIF p_origem = 'publico' AND NULLIF(btrim(p_ip_hash), '') IS NULL THEN
    v_reason := 'ip_ausente';
  ELSIF p_origem = 'link' THEN
    SELECT * INTO v_link FROM agenda.booking_links
     WHERE p_link_token ~ '^[0-9a-f]{64}$'
       AND token_sha256 = encode(sha256(convert_to(p_link_token, 'UTF8')), 'hex')
     FOR UPDATE;
    IF NOT FOUND OR v_link.revoked_at IS NOT NULL OR v_link.expires_at <= now()
       OR v_link.used_at IS NOT NULL THEN
      v_reason := 'link_invalido';
    ELSIF p_phone IS NOT NULL AND agenda.phone_key(p_phone) IS DISTINCT FROM agenda.phone_key(v_link.phone) THEN
      v_reason := 'link_invalido';
    ELSE
      v_phone := v_link.phone;
      v_name := COALESCE(p_lead_name, v_link.lead_name);
    END IF;
  END IF;

  v_key := agenda.phone_key(v_phone);
  IF v_reason IS NULL AND (v_key IS NULL OR p_starts_at IS NULL OR NULLIF(btrim(p_booked_by), '') IS NULL
     OR v_minutes IS NULL OR v_calendar IS NULL
     OR p_starts_at < now() + make_interval(hours => (agenda.setting('min_notice_hours') #>> '{}')::int)
     OR p_starts_at > now() + make_interval(days => (agenda.setting('horizon_days') #>> '{}')::int + 1)) THEN
    v_reason := 'invalido';
  END IF;

  IF v_reason IS NULL THEN
    PERFORM pg_advisory_xact_lock(hashtextextended('agenda.book:phone:' || v_key, 0));
    IF p_ip_hash IS NOT NULL THEN
      PERFORM pg_advisory_xact_lock(hashtextextended('agenda.book:ip:' || p_ip_hash, 0));
    END IF;
  END IF;

  IF v_reason IS NULL AND p_origem = 'publico' AND (
    SELECT count(*) FROM agenda.booking_requests r
     WHERE r.ip_hash = p_ip_hash AND r.created_at >= now() - interval '1 hour')
     >= (agenda.setting('agendar_por_hora_ip') #>> '{}')::int THEN
    v_reason := 'limite';
  END IF;

  IF v_reason IS NULL AND EXISTS (
    SELECT 1 FROM agenda.meetings m
     WHERE m.status IN ('booked', 'confirmed') AND m.starts_at > now()
       AND agenda.phone_key(m.phone) = v_key) THEN
    v_reason := 'ja_agendado';
  END IF;

  IF v_reason IS NULL AND p_origem = 'publico' AND EXISTS (
    SELECT 1 FROM agenda.booking_requests r
      JOIN agenda.meetings m ON m.id = r.meeting_id
     WHERE r.ip_hash = p_ip_hash AND r.resultado = 'agendado'
       AND m.status IN ('booked', 'confirmed') AND m.starts_at > now()) THEN
    v_reason := 'ja_agendado_ip';
  END IF;

  IF v_reason IS NULL THEN
    BEGIN
      INSERT INTO agenda.meetings (calendar_id, starts_at, ends_at, phone, lead_name, lead_id,
                                   ref, briefing, booked_by)
      VALUES (v_calendar, p_starts_at, p_starts_at + make_interval(mins => v_minutes), v_phone, v_name,
              v_link.lead_id, p_ref, COALESCE(p_briefing, '{}'::jsonb), p_booked_by)
      RETURNING id INTO v_meeting_id;
    EXCEPTION WHEN exclusion_violation THEN
      v_reason := 'slot_taken';
    END;
    IF v_meeting_id IS NOT NULL AND v_link.id IS NOT NULL THEN
      UPDATE agenda.booking_links SET used_at = now() WHERE id = v_link.id;
    END IF;
  END IF;

  INSERT INTO agenda.booking_requests (origem, link_id, ip_hash, phone_key, resultado, meeting_id, detalhe)
  VALUES (CASE WHEN p_origem = 'link' THEN 'link' ELSE 'publico' END, v_link.id, p_ip_hash, v_key,
          COALESCE(v_reason, 'agendado'), v_meeting_id,
          CASE WHEN v_reason IS NULL THEN '{}'::jsonb ELSE jsonb_build_object('reason', v_reason) END)
  RETURNING id INTO v_request_id;

  IF v_reason IS NOT NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', v_reason, 'request_id', v_request_id);
  END IF;
  RETURN jsonb_build_object('ok', true, 'meeting_id', v_meeting_id, 'request_id', v_request_id,
    'calendar_id', v_calendar, 'starts_at', p_starts_at,
    'ends_at', p_starts_at + make_interval(mins => v_minutes));
END
$$;

CREATE OR REPLACE FUNCTION agenda.attach_calendar_event(p_meeting_id bigint, p_event_id text, p_meet_url text)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = agenda, pg_temp AS $$
BEGIN
  UPDATE agenda.meetings SET gcal_event_id = p_event_id, meet_url = p_meet_url, updated_at = now()
   WHERE id = p_meeting_id AND gcal_event_id IS NULL;
  RETURN FOUND;
END
$$;

-- When the calendar write fails after a booking, free the slot.
CREATE OR REPLACE FUNCTION agenda.cancel_meeting(p_meeting_id bigint, p_actor text)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = agenda, pg_temp AS $$
BEGIN
  IF NULLIF(btrim(p_actor), '') IS NULL THEN
    RETURN false;
  END IF;
  UPDATE agenda.meetings SET status = 'cancelled', updated_at = now(),
         briefing = briefing || jsonb_build_object('cancelado_por', p_actor)
   WHERE id = p_meeting_id AND status IN ('booked', 'confirmed');
  RETURN FOUND;
END
$$;

-- Busy intervals already held in this database (the page merges them with
-- Google free/busy, so a booking whose event is still being created is never offered).
CREATE OR REPLACE FUNCTION agenda.busy(p_from timestamptz, p_to timestamptz)
RETURNS TABLE(starts_at timestamptz, ends_at timestamptz)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = agenda, pg_temp AS $$
  SELECT m.starts_at, m.ends_at FROM agenda.meetings m
   WHERE m.status IN ('booked', 'confirmed') AND m.starts_at < p_to AND m.ends_at > p_from
   ORDER BY m.starts_at
$$;

